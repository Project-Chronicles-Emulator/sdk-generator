bool IDAExporter::WriteBundle(
	const std::filesystem::path& workingDirectory,
	std::string_view unrealHeader,
	std::string& error)
{
	error.clear();
	const auto directory = workingDirectory / "IDA";
	std::error_code ec;
	std::filesystem::create_directories(directory, ec);
	if (ec)
	{
		error = "could not create " + directory.string() + ": " + ec.message();
		return false;
	}

	Memory::ImageInfo image;
	std::string imageError;
	const auto live = Memory::getImageInfo(image, imageError);
	const auto metadata = buildMetadata(live ? &image : nullptr);
	const auto json = metadata.dump(2, ' ', false, nlohmann::detail::error_handler_t::replace);

	const std::array<std::string, 3> names{ "unreal.h", "unreal.json", "unreal.py" };
	if (!writeText(directory / "unreal.h.tmp", unrealHeader, error) ||
		!writeText(directory / "unreal.json.tmp", json, error) ||
		!writeText(directory / "unreal.py.tmp", kPython, error))
	{
		for (const auto& name : names)
			std::filesystem::remove(directory / (name + ".tmp"), ec);
		return false;
	}

	return promote(directory, names, error);
}
