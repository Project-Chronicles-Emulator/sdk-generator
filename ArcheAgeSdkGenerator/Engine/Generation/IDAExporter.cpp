	std::string hexValue(uint64_t value)
	{
		std::ostringstream stream;
		stream << "0x" << std::uppercase << std::hex << value;
		return stream.str();
	}

	std::string sanitizeSymbol(const std::string& value)
	{
		std::string result;
		result.reserve(value.size());
		for (const auto c : value)
			result += std::isalnum(static_cast<unsigned char>(c)) || c == '_' ? c : '_';
		if (result.empty())
			result = "noname";
		if (std::isdigit(static_cast<unsigned char>(result.front())))
			result.insert(result.begin(), '_');
		return result;
	}

	std::string renderSignature(const EngineStructs::Struct& owner, const EngineStructs::Function& function)
	{
		std::ostringstream stream;
		stream << function.returnType.stringify(false) << ' ' << owner.cppName << "::" << function.cppName << '(';
		for (size_t i = 0; i < function.params.size(); ++i)
		{
			const auto& [type, name, flags, arrayDim] = function.params[i];
			if (i)
				stream << ", ";
			stream << type.stringify(false);
			if (flags & EPropertyFlags::CPF_OutParm)
				stream << '&';
			stream << ' ' << name;
			if (arrayDim > 1)
				stream << '[' << arrayDim << ']';
		}
		stream << ')';
		return stream.str();
	}

	bool isExecutableRva(const Memory::ImageInfo& image, uint64_t rva)
	{
		if (!rva || rva >= image.sizeOfImage)
			return false;
		for (const auto& section : image.sections)
		{
			const auto end = static_cast<uint64_t>(section.rva) + section.virtualSize;
			if (rva >= section.rva && rva < end)
				return (section.characteristics & IMAGE_SCN_MEM_EXECUTE) != 0;
		}
		return false;
	}

	nlohmann::json typeJson(const fieldType& type)
	{
		nlohmann::json result;
		result["name"] = type.name;
		result["rendered"] = type.stringify(false);
		result["propertyType"] = static_cast<int>(type.propertyType);
		result["pointer"] = type.isPointer();
		result["subTypes"] = nlohmann::json::array();
		for (const auto& child : type.subTypes)
			result["subTypes"].push_back(typeJson(child));
		return result;
	}

	nlohmann::json functionJson(
		const EngineStructs::Package& package,
		const EngineStructs::Struct& owner,
		const EngineStructs::Function& function)
	{
		nlohmann::json result;
		result["package"] = package.packageName;
		result["owner"] = owner.cppName;
		result["ownerFullName"] = owner.fullName;
		result["fullName"] = function.fullName;
		result["cppName"] = function.cppName;
		result["flags"] = function.functionFlags;
		result["flagsValue"] = function.functionFlagsValue;
		result["logicalSignature"] = renderSignature(owner, function);
		result["returnType"] = typeJson(function.returnType);
		result["candidateRva"] = hexValue(function.binaryOffset);
		result["parameters"] = nlohmann::json::array();
		for (const auto& [type, name, flags, arrayDim] : function.params)
		{
			result["parameters"].push_back({
				{ "name", name },
				{ "type", typeJson(type) },
				{ "propertyFlags", flags },
				{ "arrayDim", arrayDim }
			});
		}
		return result;
	}

	nlohmann::json buildMetadata(const Memory::ImageInfo* image)
	{
		nlohmann::json root;
		root["schemaVersion"] = 1;
		root["generator"] = "ArcheAgeSdkGenerator";
		root["typeMarker"] = "FArcheAgeBundle_20261023_1";
		root["engine"] = {
			{ "name", EngineSettings::getEngineVersion().name },
			{ "versionConstant", UE_VERSION }
		};
		root["module"] = {
			{ "live", image != nullptr },
			{ "name", image ? image->moduleName : EngineSettings::getTargetApplicationName() },
			{ "machine", image ? image->machine : 0 },
			{ "optionalHeaderMagic", image ? image->optionalHeaderMagic : 0 },
			{ "timeDateStamp", image ? image->timeDateStamp : 0 },
			{ "sizeOfImage", image ? image->sizeOfImage : 0 }
		};
		root["globals"] = nlohmann::json::array();
		root["types"] = nlohmann::json::array();
		root["blueprintActors"] = nlohmann::json::array();
		root["enums"] = nlohmann::json::array();
		root["functions"] = nlohmann::json::array();
		root["nativeTargets"] = nlohmann::json::array();

		if (image)
		{
			for (const auto& offset : EngineCore::getOffsets())
			{
				if (!(offset.flag & OFFSET_DS))
					continue;
				const auto address = EngineCore::getOffsetAddress(offset);
				if (address < image->imageBase || address - image->imageBase >= image->sizeOfImage)
					continue;

				std::string idaType = "void*";
				std::string description = "Resolved Unreal global";
				if (offset.name == "OFFSET_GNAMES")
				idaType = "FNamePool_IDA_UE53";
				else if (offset.name == "OFFSET_GOBJECTS")
					idaType = "FUObjectArray_IDA";
				else if (offset.name == "OFFSET_GWORLD")
					idaType = "UWorld*";

				std::ostringstream signature;
				for (size_t i = 0; i < offset.mask.size(); ++i)
				{
					if (i)
						signature << ' ';
					if (offset.mask[i] == '?')
						signature << "??";
					else
						signature << std::uppercase << std::hex << std::setw(2) << std::setfill('0')
							<< static_cast<unsigned>(static_cast<unsigned char>(offset.sig[i]));
				}

				root["globals"].push_back({
					{ "name", offset.name },
					{ "rva", hexValue(address - image->imageBase) },
					{ "idaType", idaType },
					{ "description", description },
					{ "signature", signature.str() },
					{ "mask", offset.mask }
				});
			}
		}

		struct NativeAlias
		{
			std::string package;
			std::string owner;
			nlohmann::json json;
		};
		std::map<uint64_t, std::vector<NativeAlias>> nativeAliases;

		for (const auto& package : EngineCore::getPackages())
		{
			auto exportStructs = [&](const std::vector<EngineStructs::Struct>& structs)
			{
				for (const auto& type : structs)
				{
					nlohmann::json item;
					item["package"] = package.packageName;
					item["kind"] = type.isClass ? "class" : "struct";
					item["fullName"] = type.fullName;
					item["cppName"] = type.cppName;
					item["size"] = type.size;
					item["maxSize"] = type.maxSize;
					item["alignment"] = type.minAlignment;
					item["supers"] = type.superNames;
					const auto blueprintActor = type.isClass &&
						type.fullName.starts_with("/Game/") &&
						type.cppName.ends_with("_C") &&
						std::ranges::find(type.superNames, "AActor") != type.superNames.end();
					item["blueprintActor"] = blueprintActor;
					item["fields"] = nlohmann::json::array();

					for (const auto& cooked : type.cookedMembers)
					{
						const auto& member = cooked.first
							? type.definedMembers.at(cooked.second)
							: type.undefinedMembers.at(cooked.second);
						item["fields"].push_back({
							{ "name", member.name },
							{ "type", typeJson(member.type) },
							{ "offset", member.offset },
							{ "size", member.size },
							{ "arrayDim", member.arrayDim },
							{ "bitfield", member.isBit },
							{ "bitOffset", member.bitOffset },
							{ "generatedPadding", member.missed }
						});
					}
					root["types"].push_back(item);
					if (blueprintActor)
					{
						root["blueprintActors"].push_back({
							{ "cppName", type.cppName },
							{ "fullName", type.fullName },
							{ "package", package.packageName },
							{ "size", type.maxSize },
							{ "super", type.superNames.empty() ? "" : type.superNames.front() },
							{ "fieldCount", type.cookedMembers.size() },
							{ "functionCount", type.functions.size() }
						});
					}

					for (const auto& function : type.functions)
					{
						auto functionData = functionJson(package, type, function);
						root["functions"].push_back(functionData);
						if (image && (function.functionFlagsValue & FUNC_Native) &&
							isExecutableRva(*image, function.binaryOffset))
						{
							nativeAliases[function.binaryOffset].push_back({
								package.packageName,
								type.cppName,
								{
									{ "fullName", function.fullName },
									{ "flags", function.functionFlags },
									{ "logicalSignature", renderSignature(type, function) },
									{ "group", package.packageName + "/" + type.cppName }
								}
							});
						}
					}
				}
			};
			exportStructs(package.structs);
			exportStructs(package.classes);

			for (const auto& unrealEnum : package.enums)
			{
				nlohmann::json values = nlohmann::json::array();
				for (const auto& [name, value] : unrealEnum.members)
					values.push_back({ { "name", name }, { "value", value } });
				root["enums"].push_back({
					{ "package", package.packageName },
					{ "fullName", unrealEnum.fullName },
					{ "cppName", unrealEnum.cppName },
					{ "underlyingType", unrealEnum.type },
					{ "size", unrealEnum.size },
					{ "values", std::move(values) }
				});
			}
		}

		std::unordered_map<std::string, uint64_t> usedNames;
		for (auto& [rva, aliases] : nativeAliases)
		{
			std::ranges::sort(aliases, [](const NativeAlias& left, const NativeAlias& right)
			{
				return left.json["fullName"].get<std::string>() < right.json["fullName"].get<std::string>();
			});

			const auto& first = aliases.front();
			std::string name = "exec_" + sanitizeSymbol(first.package) + "_" +
				sanitizeSymbol(first.owner) + "_" +
				sanitizeSymbol(first.json["fullName"].get<std::string>());
			if (name.size() > 200)
				name.resize(200);
			if (const auto it = usedNames.find(name); it != usedNames.end() && it->second != rva)
				name += "_" + hexValue(rva).substr(2);
			usedNames[name] = rva;

			nlohmann::json aliasJson = nlohmann::json::array();
			for (auto& alias : aliases)
				aliasJson.push_back(std::move(alias.json));
			root["nativeTargets"].push_back({
				{ "rva", hexValue(rva) },
				{ "name", name },
				{ "aliases", std::move(aliasJson) }
			});
		}

		std::sort(root["blueprintActors"].begin(), root["blueprintActors"].end(), [](const auto& left, const auto& right)
		{
			return left["fullName"].template get<std::string>() <
				right["fullName"].template get<std::string>();
		});
		return root;
	}

	bool writeText(const std::filesystem::path& path, std::string_view content, std::string& error)
	{
		std::ofstream stream(path, std::ios::binary | std::ios::trunc);
		if (!stream)
		{
			error = "could not open " + path.string();
			return false;
		}
		stream.write(content.data(), static_cast<std::streamsize>(content.size()));
		stream.close();
		if (!stream)
		{
			error = "could not finish writing " + path.string();
			return false;
		}
		return true;
	}

	bool promote(
		const std::filesystem::path& directory,
		const std::array<std::string, 3>& names,
		std::string& error)
	{
		std::error_code ec;
		std::vector<std::string> backedUp;
		std::vector<std::string> promoted;

		for (const auto& name : names)
		{
			const auto finalPath = directory / name;
			const auto backupPath = directory / (name + ".bak");
			std::filesystem::remove(backupPath, ec);
			ec.clear();
			if (std::filesystem::exists(finalPath))
			{
				std::filesystem::rename(finalPath, backupPath, ec);
				if (ec)
				{
					error = "could not back up " + finalPath.string() + ": " + ec.message();
					goto rollback;
				}
				backedUp.push_back(name);
			}
		}

		for (const auto& name : names)
		{
			std::filesystem::rename(directory / (name + ".tmp"), directory / name, ec);
			if (ec)
			{
				error = "could not publish " + name + ": " + ec.message();
				goto rollback;
			}
			promoted.push_back(name);
		}

		for (const auto& name : backedUp)
			std::filesystem::remove(directory / (name + ".bak"), ec);
		return true;

	rollback:
		for (const auto& name : promoted)
			std::filesystem::remove(directory / name, ec);
		for (const auto& name : backedUp)
		{
			ec.clear();
			std::filesystem::rename(directory / (name + ".bak"), directory / name, ec);
		}
		for (const auto& name : names)
			std::filesystem::remove(directory / (name + ".tmp"), ec);
		return false;
	}
